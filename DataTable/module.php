    /**
     * Converts a value to the storage type of the field. Returns [ok, value];
     * ok is false when a non-empty value cannot be converted without loss.
     */
    private function CastValue(array $Field, mixed $Value): array
    {
        if (is_array($Value) || is_object($Value)) {
            return [false, null];
        }
        $Empty = $Value === null || (is_string($Value) && trim($Value) === '');
        switch ($Field['store']) {
            case 'boolean':
                if (is_string($Value)) {
                    return [true, in_array(strtolower(trim($Value)), ['1', 'true', 'on', 'yes', 'ja'], true)];
                }
                return [true, (bool)$Value];
            case 'integer':
                if ($Empty) {
                    return [true, null];
                }
                if (is_bool($Value)) {
                    return [true, $Value ? 1 : 0];
                }
                $Value = str_replace(',', '.', trim((string)$Value));
                if (!is_numeric($Value) || (float)$Value != (int)$Value) {
                    return [false, null];
                }
                return [true, (int)$Value];
            case 'float':
                if ($Empty) {
                    return [true, null];
                }
                if (is_bool($Value)) {
                    return [true, $Value ? 1.0 : 0.0];
                }
                $Value = str_replace(',', '.', trim((string)$Value));
                if (!is_numeric($Value)) {
                    return [false, null];
                }
                return [true, round((float)$Value, (int)$Field['digits'])];
            default:
                if ($Empty) {
                    return [true, ''];
                }
                if (is_bool($Value)) {
                    $Value = $Value ? '1' : '0';
                }
                $Value = (string)$Value;
                if (($Field['format'] ?? '') === 'date') {
                    $Value = trim($Value);
                    if (preg_match('/^(\d{1,2})\.(\d{1,2})\.(\d{4})$/', $Value, $M)) {
                        $Value = sprintf('%04d-%02d-%02d', $M[3], $M[2], $M[1]);
                    }
                    if (!preg_match('/^(\d{4})-(\d{2})-(\d{2})$/', $Value, $M) || !checkdate((int)$M[2], (int)$M[3], (int)$M[1])) {
                        return [false, ''];
                    }
                }
                return [true, $Value];
        }
    }

    private function IsEmptyValue(array $Field, mixed $Value): bool
    {
        if ($Field['store'] === 'boolean') {
            return false;
        }
        return $Value === null || (is_string($Value) && trim($Value) === '');
    }

    private function BuildKey(array $Values, array $Schema): string
    {
        $KeyFields = array_values(array_filter($Schema['fields'], static fn(array $Field): bool => $Field['key'] !== null));
        usort($KeyFields, static fn(array $A, array $B): int => $A['key'] <=> $B['key']);

        $Parts = [];
        foreach ($KeyFields as $Field) {
            $Value = $Values[$Field['id']] ?? '';
            if ($Field['store'] === 'boolean') {
                $Part = $Value ? '1' : '0';
            } else {
                $Part = trim(str_replace("\t", ' ', (string)$Value));
            }
            if ($Field['store'] === 'string' && !$Field['caseSensitive']) {
                $Part = mb_strtolower($Part, 'UTF-8');
            }
            $Parts[] = $Part;
        }
        return implode("\t", $Parts);
    }

    /**
     * Adapts all records to a new schema: missing fields get their default,
     * values are converted to the new type and keys are rebuilt. Values of
     * removed fields are kept. Fails without changing anything if a value
     * cannot be converted, a key field is empty or two records get the same key.
     * Returns [data, null] or [null, error message].
     */
    private function MigrateData(array $Data, array $Schema): array
    {
        $Result = [];
        foreach ($Data as $OldKey => $Entry) {
            $Old = is_array($Entry['v'] ?? null) ? $Entry['v'] : [];
            $Values = [];
            foreach ($Schema['fields'] as $Field) {
                if (!array_key_exists($Field['id'], $Old)) {
                    $Values[$Field['id']] = $Field['default'];
                    continue;
                }
                [$Ok, $Value] = $this->CastValue($Field, $Old[$Field['id']]);
                if (!$Ok) {
                    return [null, sprintf($this->Translate('Field %s: the value "%s" cannot be converted to the new type.'),
                        $Field['name'], $this->ShortText($Old[$Field['id']]))];
                }
                $Values[$Field['id']] = $Value;
            }
            $Values += $Old;

            foreach ($Schema['fields'] as $Field) {
                if ($Field['key'] !== null && $this->IsEmptyValue($Field, $Values[$Field['id']])) {
                    return [null, sprintf($this->Translate('Key field %s is empty in at least one record. Give the field a default value.'), $Field['name'])];
                }
            }
            $Key = $this->BuildKey($Values, $Schema);
            if (isset($Result[$Key])) {
                return [null, sprintf($this->Translate('Two records would get the same key (%s).'), str_replace("\t", ' / ', $Key))];
            }
            $Rev = (int)($Entry['rev'] ?? 0);
            $Changed = (string)$OldKey !== $Key || !$this->SameValues($Values, $Old);
            $Result[$Key] = ['rev' => $Changed ? $Rev + 1 : max(1, $Rev), 'v' => $Values];
        }
        return [$Result, null];
    }

    private function SameValues(array $A, array $B): bool
    {
        ksort($A);
        ksort($B);
        return $A === $B;
    }

    private function ShortText(mixed $Value): string
    {
        $Text = is_scalar($Value) ? (string)$Value : (string)json_encode($Value);
        return mb_strlen($Text) > 40 ? mb_substr($Text, 0, 40) . '…' : $Text;
    }

    // ---------------------------------------------------------------------
    // Store and messaging
    // ---------------------------------------------------------------------

    private function ReadData(): array
    {
        $Data = json_decode($this->ReadAttributeString('Data'), true);
        return is_array($Data) ? $Data : [];
    }

    private function WriteData(array $Data): void
    {
        $this->WriteAttributeString('Data', (string)json_encode((object)$Data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));
    }

    private function Lock(): bool
    {
        return IPS_SemaphoreEnter('DATAT_' . $this->InstanceID, self::LOCK_TIMEOUT);
    }

    private function Unlock(): void
    {
        IPS_SemaphoreLeave('DATAT_' . $this->InstanceID);
    }

    private function RecordMessagePart(string $Key, array $Entry): array
    {
        return ['k' => $Key, 'rev' => (int)$Entry['rev'], 'v' => (object)$Entry['v']];
    }

    private function BuildFullMessage(?string $Client): array
    {
        $Schema = $this->GetActiveSchema();
        $Records = [];
        if ($Schema !== null) {
            foreach ($this->ReadData() as $Key => $Entry) {
                $Records[] = $this->RecordMessagePart((string)$Key, $Entry);
            }
        }
        $Error = $this->ReadAttributeString('ConfigError');
        return [
            't'       => 'full',
            'c'       => $Client,
            'schema'  => $Schema ?? ['title' => trim($this->ReadPropertyString('Title')), 'fields' => []],
            'records' => $Records,
            'error'   => $Error !== '' ? $Error : null,
            'texts'   => array_combine(self::TILE_TEXTS, array_map(fn(string $Text): string => $this->Translate($Text), self::TILE_TEXTS))
        ];
    }

    private function SendError(string $Client, int $RequestID, string $Code, string $Message, ?array $Record = null): void
    {
        $this->Broadcast(['t' => 'error', 'c' => $Client, 'r' => $RequestID, 'code' => $Code, 'msg' => $Message, 'rec' => $Record]);
    }

    private function Broadcast(array $Message): void
    {
        $Json = json_encode($Message, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
        if ($Json !== false) {
            $this->UpdateVisualizationValue($Json);
        }
    }

    private function VisualizationType(): int
    {
        // Same approach as ImageSlider: fullscreen HTML tiles (type 2) from 9.1.
        return version_compare(IPS_GetKernelVersion(), '9.1', '>=') ? 2 : 1;
    }
