    public function Create(): void
    {
        parent::Create();

        $this->RegisterPropertyString('Title', '');
        $this->RegisterPropertyString('RecordTitle', '');   // e.g. "{chapter} - {title_de}"
        $this->RegisterPropertyString('SortOrder', '');     // e.g. "chapter, -order, tag"
        $this->RegisterPropertyString('KeyFields', '[]');
        $this->RegisterPropertyString('DataFields', '[]');

        $this->RegisterAttributeString('Data', '{}');        // {key: {rev, v: {fieldID: value}}}
        $this->RegisterAttributeString('Schema', '');        // schema the stored data follows
        $this->RegisterAttributeString('ConfigError', '');
        $this->RegisterAttributeInteger('NextFieldID', 1);

        $this->SetVisualizationType($this->VisualizationType());
    }

    public function ApplyChanges(): void
    {
        parent::ApplyChanges();
        $this->SetVisualizationType($this->VisualizationType());

        // New rows get their ID (a field moved between the lists keeps the ID of
        // its name) and every row its summary. Stored, then applied once more.
        $Keys = $this->ReadRows('KeyFields');
        $Fields = $this->ReadRows('DataFields');
        $Changed = $this->AssignFieldIDs($Keys, $Fields);
        foreach ([&$Keys, &$Fields] as &$Rows) {
            foreach ($Rows as &$Row) {
                $Details = $this->Details($Row);
                if ($Row['Details'] !== $Details) {
                    $Row['Details'] = $Details;
                    $Changed = true;
                }
                // The dialog checkbox only reveals settings; it is not part of the definition.
                if (!empty($Row['Advanced'])) {
                    $Row['Advanced'] = false;
                    $Changed = true;
                }
            }
            unset($Row);
        }
        unset($Rows);
        if ($Changed) {
            IPS_SetProperty($this->InstanceID, 'KeyFields', json_encode($Keys, JSON_UNESCAPED_UNICODE));
            IPS_SetProperty($this->InstanceID, 'DataFields', json_encode($Fields, JSON_UNESCAPED_UNICODE));
            IPS_ApplyChanges($this->InstanceID);
            return;
        }

        if (count($Keys) + count($Fields) === 0) {
            $this->Fail(self::STATUS_NO_FIELDS, $this->Translate('No fields defined yet.'));
            return;
        }
        [$Schema, $Error] = $this->BuildSchema($Keys, $Fields);
        if ($Schema === null) {
            $this->Fail(self::STATUS_INVALID_FIELDS, $Error);
            return;
        }

        // Adapt the stored records when the definition has changed. If that is not
        // possible without losing data, nothing is changed and the error is shown.
        $SchemaJson = (string)json_encode($Schema, JSON_UNESCAPED_UNICODE);
        if ($SchemaJson !== $this->ReadAttributeString('Schema')) {
            if (!$this->Lock()) {
                $this->Fail(self::STATUS_MIGRATION, $this->Translate('Data store is locked.'));
                return;
            }
            try {
                [$Data, $Error] = $this->MigrateData($this->ReadData(), $Schema);
                if ($Data === null) {
                    $this->Fail(self::STATUS_MIGRATION, $Error);
                    return;
                }
                $this->WriteData($Data);
                $this->WriteAttributeString('Schema', $SchemaJson);
            } finally {
                $this->Unlock();
            }
        }

        $this->WriteAttributeString('ConfigError', '');
        $this->SetStatus(IS_ACTIVE);
        $this->Broadcast($this->BuildFullMessage(null));
    }

    public function GetConfigurationForm(): string
    {
        $Form = json_decode((string)file_get_contents(__DIR__ . '/form.json'), true);

        $Error = $this->ReadAttributeString('ConfigError');
        if ($Error !== '') {
            array_unshift($Form['elements'], ['type' => 'Label', 'caption' => '⚠ ' . $Error, 'bold' => true]);
        }

        // Dialog: type dependent settings start hidden. The checkbox "Show
        // advanced settings" shows the ones that apply to the type (and follows
        // changes of type, display and options while it is set). Symcon keeps
        // that visibility when the dialog is opened again, so closing the dialog
        // with OK (onEdit/onAdd) hides them again. Cancel has no event.
        foreach ($Form['elements'] as &$Element) {
            if (!in_array($Element['name'] ?? '', ['KeyFields', 'DataFields'], true)) {
                continue;
            }
            $List = $Element['name'] === 'KeyFields' ? 'keys' : 'data';
            $Script = "IPS_RequestAction(\$id, 'Dialog', json_encode(['list' => '" . $List . "', "
                . "'type' => isset(\$Type) ? \$Type : '', 'format' => isset(\$Format) ? \$Format : '', "
                . "'options' => isset(\$Options) ? \$Options : '', 'advanced' => isset(\$Advanced) ? (bool)\$Advanced : false]));";
            // Tested: onEdit fires when the dialog is closed with OK (not on cancel).
            foreach (['onEdit', 'onAdd'] as $Event) {
                $Element[$Event] = "IPS_RequestAction(\$id, 'Dialog', json_encode(['list' => '" . $List . "', 'reset' => '" . $Event . "']));";
            }
            foreach ($Element['columns'] as &$Column) {
                if (in_array($Column['name'], ['Type', 'Format', 'Options', 'Advanced'], true) && isset($Column['edit'])) {
                    $Column['edit']['onChange'] = $Script;
                }
            }
            unset($Column);
        }
        unset($Element);

        return (string)json_encode($Form);
    }

    public function GetVisualizationTile(): string
    {
        $Html = file_get_contents(__DIR__ . '/assets/index.html');
        if ($Html === false) {
            return '';
        }
        $Flags = JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_UNESCAPED_UNICODE;
        $Message = json_encode($this->BuildFullMessage(null), $Flags);
        return str_replace(
            '</body>',
            '<script>handleMessage(' . json_encode($Message !== false ? $Message : '{}', $Flags) . ');</script></body>',
            $Html
        );
    }

    public function RequestAction(string $Ident, mixed $Value): void
    {
        switch ($Ident) {
            case 'Request':
                $this->HandleTileRequest((string)$Value);
                break;
            case 'Dialog':
                $this->HandleDialogChange((string)$Value);
                break;
            default:
                throw new Exception('Invalid Ident: ' . $Ident);
        }
    }

