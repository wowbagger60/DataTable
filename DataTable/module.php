    /** Shows only the dialog settings that apply to the chosen type. */
    private function HandleDialogChange(string $Json): void
    {
        $Request = json_decode($Json, true);
        if (!is_array($Request)) {
            return;
        }
        $IsKey = ($Request['list'] ?? '') === 'keys';
        $Type = in_array($Request['type'] ?? '', self::TYPES, true) ? (string)$Request['type'] : 'string';
        $Format = (string)($Request['format'] ?? '');
        $HasOptions = trim((string)($Request['options'] ?? '')) !== '';
        $Reset = isset($Request['reset']);
        if ($Reset) {
            $this->SendDebug('Dialog', 'List event ' . (string)$Request['reset'] . ' (' . ($IsKey ? 'KeyFields' : 'DataFields') . ')', 0);
        }
        $Show = !$Reset && !empty($Request['advanced']);
        foreach ($this->DialogVisibility($IsKey, $Type, $Format, $HasOptions) as $Column => $Visible) {
            // Required is a general setting; only Boolean fields hide it.
            $this->UpdateFormField($Column, 'visible', $Column === 'Required' ? ($Reset || $Visible) : ($Show && $Visible));
        }
    }

    /** Type dependent columns of the dialog and whether they apply. */
    private function DialogVisibility(bool $IsKey, string $Type, string $Format, bool $HasOptions): array
    {
        $Format = $Type === 'string' && in_array($Format, self::FORMATS, true) ? $Format : 'line';
        $CanHaveOptions = $Type === 'integer' || $Type === 'boolean' || ($Type === 'string' && $Format === 'line');
        $Visible = [
            'Format'  => $Type === 'string',
            'Options' => $CanHaveOptions,
            'Filter'  => $Type === 'boolean' || ($CanHaveOptions && $HasOptions),
            'Min'     => $Type === 'float' || ($Type === 'integer' && !$HasOptions),
            'Max'     => $Type === 'float' || ($Type === 'integer' && !$HasOptions),
            'Prefix'  => $Type === 'integer' || $Type === 'float',
            'Suffix'  => $Type === 'integer' || $Type === 'float',
            'Digits'  => $Type === 'float'
        ];
        if ($IsKey) {
            $Visible['CaseSensitive'] = $Type === 'string';
        } else {
            $Visible['Rows'] = $Type === 'string' && $Format === 'multiline';
            $Visible['Required'] = $Type !== 'boolean';
        }
        return $Visible;
    }

    /** Short description of a field for the lists. */
    private function Details(array $Row): string
    {
        $Row = array_merge(self::ROW_DEFAULTS, $Row);
        $Parts = [];
        $Options = $this->ParseOptions((string)$Row['Options']);
        if (count($Options) > 0 && $Row['Type'] !== 'float') {
            $Parts[] = sprintf($this->Translate('Selection (%d)'), count($Options));
        } elseif ($Row['Type'] === 'string') {
            $Parts[] = $this->Translate(['line' => 'Single line', 'multiline' => 'Multi-line', 'date' => 'Date'][$Row['Format']] ?? 'Single line');
        } elseif ($Row['Type'] === 'boolean') {
            $Parts[] = $this->Translate('Switch');
        } else {
            if ($Row['Type'] === 'float') {
                $Parts[] = sprintf($this->Translate('%d decimals'), (int)$Row['Digits']);
            }
            if ($Row['Min'] !== '' || $Row['Max'] !== '') {
                $Parts[] = ($Row['Min'] !== '' ? $Row['Min'] : '…') . ' – ' . ($Row['Max'] !== '' ? $Row['Max'] : '…');
            }
        }
        if ($Row['Prefix'] !== '' || $Row['Suffix'] !== '') {
            $Parts[] = trim($Row['Prefix'] . ' … ' . $Row['Suffix']);
        }
        if ($Row['Default'] !== '') {
            $Parts[] = $this->Translate('Default') . ' ' . $Row['Default'];
        }
        if ($Row['Filter'] && ($Row['Type'] === 'boolean' || (count($Options) > 0 && $Row['Type'] !== 'float'))) {
            $Parts[] = $this->Translate('Filter');
        }
        return implode(' · ', $Parts);
    }

    // ---------------------------------------------------------------------
    // Field definition
    // ---------------------------------------------------------------------

    private function ReadRows(string $Property): array
    {
        $Rows = json_decode($this->ReadPropertyString($Property), true);
        if (!is_array($Rows)) {
            return [];
        }
        $Result = [];
        foreach ($Rows as $Row) {
            if (is_array($Row)) {
                $Result[] = array_merge(self::ROW_DEFAULTS, $Row);
            }
        }
        return $Result;
    }

    /**
     * Gives every row without ID (or with a duplicate one) an ID: the ID its
     * name had in the applied schema (field moved between the lists or
     * re-created), otherwise a new one. Returns true if anything changed.
     */
    private function AssignFieldIDs(array &$Keys, array &$Fields): bool
    {
        $Known = [];
        $Schema = json_decode($this->ReadAttributeString('Schema'), true);
        foreach (is_array($Schema['fields'] ?? null) ? $Schema['fields'] : [] as $Field) {
            $Known[strtolower((string)$Field['name'])] = (string)$Field['id'];
        }

        $Next = $this->ReadAttributeInteger('NextFieldID');
        $Seen = [];
        foreach (array_merge($Keys, $Fields) as $Row) {
            if (preg_match('/^f(\d+)$/', (string)$Row['ID'], $Match)) {
                $Next = max($Next, (int)$Match[1] + 1);
            }
        }
        foreach ($Known as $ID) {
            if (preg_match('/^f(\d+)$/', $ID, $Match)) {
                $Next = max($Next, (int)$Match[1] + 1);
            }
        }
        // IDs that rows already carry are taken first.
        foreach (array_merge($Keys, $Fields) as $Row) {
            if ((string)$Row['ID'] !== '') {
                $Seen[(string)$Row['ID']] = ($Seen[(string)$Row['ID']] ?? 0) + 1;
            }
        }

        $Changed = false;
        $Used = [];
        foreach ([&$Keys, &$Fields] as &$Rows) {
            foreach ($Rows as &$Row) {
                $ID = (string)$Row['ID'];
                if ($ID === '' || isset($Used[$ID])) {
                    $Candidate = $Known[strtolower(trim((string)$Row['Name']))] ?? '';
                    $ID = ($Candidate !== '' && !isset($Seen[$Candidate]) && !isset($Used[$Candidate])) ? $Candidate : 'f' . $Next++;
                    $Row['ID'] = $ID;
                    $Changed = true;
                }
                $Used[$ID] = true;
            }
            unset($Row);
        }
        unset($Rows);
        $this->WriteAttributeInteger('NextFieldID', $Next);
        return $Changed;
    }

    /**
     * Validates the configured rows and builds the schema used by the tile and
     * the operations. Returns [schema, null] or [null, error message].
     *
     * Each schema field has the storage type 'store' (string, integer, float,
     * boolean) and the input type 'type' used by the tile (text, textarea,
     * date, int, float, bool, select).
     */
    private function BuildSchema(array $Keys, array $DataFields): array
    {
        if (count($Keys) === 0) {
            return [null, $this->Translate('At least one key field is required.')];
        }

        $Fields = [];
        $Names = [];
        $KeySort = [];
        $ByName = [];
        $Filter = null;

        $All = [];
        foreach ($Keys as $Index => $Row) {
            $All[] = [$Row, $Index + 1];
        }
        foreach ($DataFields as $Row) {
            $All[] = [$Row, null];
        }

        foreach ($All as [$Row, $KeyPos]) {
            $Name = trim((string)$Row['Name']);
            if (!preg_match('/^[A-Za-z][A-Za-z0-9_-]*$/', $Name)) {
                return [null, sprintf($this->Translate('Field "%s": the name must start with a letter and contain only letters, digits, _ and -.'), $Name)];
            }
            $Lower = strtolower($Name);
            if (isset($Names[$Lower])) {
                return [null, sprintf($this->Translate('The name %s is used more than once.'), $Name)];
            }
            $Names[$Lower] = true;

            $Store = (string)$Row['Type'];
            if (!in_array($Store, self::TYPES, true)) {
                return [null, $Name . ': ' . $this->Translate('Unknown type.')];
            }
            $Format = $Store === 'string' && in_array($Row['Format'], self::FORMATS, true) ? (string)$Row['Format'] : 'line';
            if ($KeyPos !== null && $Format === 'multiline') {
                return [null, $Name . ': ' . $this->Translate('A multi-line text cannot be part of the key.')];
            }

            $Field = [
                'id'            => (string)$Row['ID'],
                'name'          => $Name,
                'label'         => trim((string)$Row['Label']) !== '' ? trim((string)$Row['Label']) : $Name,
                'store'         => $Store,
                'type'          => '',
                'key'           => $KeyPos,
                'required'      => $KeyPos === null && !empty($Row['Required']),
                'list'          => !empty($Row['List']),
                'separator'     => $KeyPos === null && !empty($Row['Separator']),
                'tab'           => $KeyPos === null ? trim((string)$Row['Tab']) : '',
                'listLabel'     => trim((string)$Row['ListLabel']),
                'prefix'        => in_array($Store, ['integer', 'float'], true) ? trim((string)$Row['Prefix']) : '',
                'suffix'        => in_array($Store, ['integer', 'float'], true) ? trim((string)$Row['Suffix']) : '',
                'digits'        => max(0, min(6, (int)$Row['Digits'])),
                'rows'          => max(1, min(20, (int)$Row['Rows'])),
                'caseSensitive' => $KeyPos !== null && !empty($Row['CaseSensitive']),
                'min'           => null,
                'max'           => null,
                'options'       => [],
                'default'       => null
            ];

            // Options make String (single line), Integer and Boolean a selection.
            $OptionText = trim((string)$Row['Options']);
            $CanHaveOptions = $Store === 'integer' || $Store === 'boolean' || ($Store === 'string' && $Format === 'line');
            if ($OptionText !== '' && $CanHaveOptions) {
                foreach ($this->ParseOptions($OptionText) as $Option) {
                    [$Ok, $Value] = $this->CastValue($Field, $Option['value']);
                    if (!$Ok || $this->IsEmptyValue($Field, $Value) || ($Store === 'boolean' && !$this->IsBooleanText($Option['value']))) {
                        return [null, sprintf($this->Translate('%s: the option value "%s" does not match the type.'), $Name, $Option['value'])];
                    }
                    $Field['options'][] = ['value' => $Value, 'label' => $Option['label']];
                }
                $Values = array_map(static fn($V): string => var_export($V, true), array_column($Field['options'], 'value'));
                if (count($Values) !== count(array_unique($Values))) {
                    return [null, $Name . ': ' . $this->Translate('Option values must be unique.')];
                }
            }
            $Field['type'] = count($Field['options']) > 0 ? 'select' : match ($Store) {
                'integer' => 'int',
                'float'   => 'float',
                'boolean' => 'bool',
                default   => ['line' => 'text', 'multiline' => 'textarea', 'date' => 'date'][$Format]
            };
            if ($Format === 'date' && $Field['type'] === 'date') {
                $Field['format'] = 'date';
            }

            if ($Field['type'] === 'int' || $Field['type'] === 'float') {
                foreach (['Min' => 'min', 'Max' => 'max'] as $Column => $Prop) {
                    $Text = str_replace(',', '.', trim((string)$Row[$Column]));
                    if ($Text === '') {
                        continue;
                    }
                    if (!is_numeric($Text)) {
                        return [null, $Name . ': ' . $this->Translate('Minimum and maximum must be numbers.')];
                    }
                    $Field[$Prop] = $Store === 'integer' ? (int)$Text : (float)$Text;
                }
                if ($Field['min'] !== null && $Field['max'] !== null && $Field['min'] > $Field['max']) {
                    return [null, $Name . ': ' . $this->Translate('Minimum is greater than maximum.')];
                }
            }

            $DefaultText = trim((string)$Row['Default']);
            if ($Store === 'boolean') {
                $Field['default'] = $DefaultText !== '' && $this->IsBooleanText($DefaultText) && in_array(strtolower($DefaultText), ['1', 'true', 'yes', 'ja', 'on'], true);
                if ($DefaultText !== '' && !$this->IsBooleanText($DefaultText)) {
                    return [null, $Name . ': ' . $this->Translate('The default value does not match the type.')];
                }
            } elseif ($DefaultText === '') {
                $Field['default'] = $Store === 'string' ? '' : null;
            } else {
                [$Ok, $Default] = $this->CastValue($Field, $DefaultText);
                if (!$Ok || (count($Field['options']) > 0 && !in_array($Default, array_column($Field['options'], 'value'), true))) {
                    return [null, $Name . ': ' . $this->Translate('The default value does not match the type.')];
                }
                $Field['default'] = $Default;
            }

            if ($KeyPos !== null) {
                $KeySort[] = ['id' => $Field['id'], 'dir' => 1];
            }
            $ByName[strtolower($Name)] = $Field['id'];
            // Filter: fields with options, and Boolean fields (yes/no) anyway.
            if (!empty($Row['Filter']) && (count($Field['options']) > 0 || $Store === 'boolean')) {
                if ($Filter !== null) {
                    return [null, $this->Translate('Only one field can be used as filter.')];
                }
                $Filter = $Field['id'];
            }

            $Fields[] = $Field;
        }

        // Sort order: "name, -name, ..." ("-" = descending); empty = key fields ascending.
        $Sort = [];
        foreach (preg_split('/[,;\s]+/', preg_replace('/([-+])\s+/', '$1', trim($this->ReadPropertyString('SortOrder'))), -1, PREG_SPLIT_NO_EMPTY) as $Part) {
            $Dir = 1;
            if ($Part[0] === '-' || $Part[0] === '+') {
                $Dir = $Part[0] === '-' ? -1 : 1;
                $Part = substr($Part, 1);
            }
            $ID = $ByName[strtolower($Part)] ?? null;
            if ($ID === null) {
                return [null, sprintf($this->Translate('Sort order: unknown field %s.'), $Part)];
            }
            $Sort[] = ['id' => $ID, 'dir' => $Dir];
        }
        // The key fields follow as tie-breakers, so the order is always unique.
        $Used = array_column($Sort, 'id');
        foreach ($KeySort as $Entry) {
            if (!in_array($Entry['id'], $Used, true)) {
                $Sort[] = $Entry;
            }
        }

        return [[
            'title'   => trim($this->ReadPropertyString('Title')),
            'fields'  => $Fields,
            'sort'    => $Sort,
            // Record title: {name} placeholders; unknown placeholders stay as text.
            'recordTitle' => trim($this->ReadPropertyString('RecordTitle')),
            'filter'  => $Filter
        ], null];
    }

    /** "value=Label; value2=Label 2" (or one per line). Without "=" value and label are the same. */
    private function ParseOptions(string $Text): array
    {
        $Options = [];
        foreach (preg_split('/[;\r\n]+/', $Text) ?: [] as $Part) {
            $Part = trim($Part);
            if ($Part === '') {
                continue;
            }
            $Pos = strpos($Part, '=');
            $Value = $Pos === false ? $Part : trim(substr($Part, 0, $Pos));
            $Label = $Pos === false ? $Part : trim(substr($Part, $Pos + 1));
            $Options[] = ['value' => $Value, 'label' => $Label !== '' ? $Label : $Value];
        }
        return $Options;
    }

    private function IsBooleanText(string $Text): bool
    {
        return in_array(strtolower(trim($Text)), ['1', '0', 'true', 'false', 'yes', 'no', 'ja', 'nein', 'on', 'off'], true);
    }

    private function GetActiveSchema(): ?array
    {
        if ($this->ReadAttributeString('ConfigError') !== '') {
            return null;
        }
        $Schema = json_decode($this->ReadAttributeString('Schema'), true);
        return is_array($Schema) && is_array($Schema['fields'] ?? null) ? $Schema : null;
    }

    private function Fail(int $Status, string $Message): void
    {
        $this->WriteAttributeString('ConfigError', $Message);
        $this->SetStatus($Status);
        $this->SendDebug('Configuration', $Message, 0);
        $this->Broadcast($this->BuildFullMessage(null));
    }

