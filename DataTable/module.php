<?php declare(strict_types=1);

/**
 * DataTable – manages small structured data sets in Symcon, edited in a tile.
 *
 * The table is described in the instance configuration by two lists: key
 * fields (their order is the key order) and data fields. Every field carries
 * a stable ID (f1, f2, …). Records store their values under these IDs, so a
 * field can be renamed or moved between the lists without losing data. The
 * public API speaks field names.
 *
 * Field types follow Symcon: String, Integer, Float, Boolean. A String is
 * shown single-line, multi-line or as date. String, Integer and Boolean
 * fields with options become a selection.
 *
 * Configuration form: fields are edited in the standard edit dialog of the
 * two lists. Symcon has no event when the dialog opens, so the dialog starts
 * with the general settings only; the checkbox "Show advanced settings" or a
 * change of type/display/options shows the settings that apply to the type
 * (RequestAction 'Dialog' -> UpdateFormField). Settings that do not fit the
 * type are ignored. Symcon only keeps list columns that have an edit
 * element, so ID has a disabled one and Details a hidden one.
 *
 * Protocol between tile and module (all messages are JSON strings):
 *   Tile -> module: requestAction('Request', {c, r, op, ...})
 *       c  = client ID generated by each tile instance
 *       r  = request number of that client
 *       op = 'save' | 'delete' | 'reload'
 *   Module -> all tiles: UpdateVisualizationValue(...)
 *       {t: 'full', c, schema, records, error}   complete state (c = null: for all clients)
 *       {t: 'changed', c, r, op, old, key, rec}  a record was saved or deleted
 *       {t: 'error', c, r, code, msg, rec}       error, relevant only for client c
 */
class DataTable extends IPSModuleStrict
{
